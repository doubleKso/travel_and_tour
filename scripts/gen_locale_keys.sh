#!/usr/bin/env bash
# Regenerates EpicWorld/Core/Config/LocaleKeys.swift from the Flutter app's
# lib/l10n/locale_keys.g.dart, so Swift call sites read exactly like Dart:
#
#   Dart:  LocaleKeys.auth_sign_in.tr()
#   Swift: LocaleKeys.auth_sign_in.tr()
#
# Run after `dart run easy_localization:generate …` refreshes the Dart file.
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
SRC="$REPO/lib/l10n/locale_keys.g.dart"
OUT="$HERE/EpicWorld/Core/Config/LocaleKeys.swift"

mkdir -p "$(dirname "$OUT")"
{
  echo "// GENERATED by ios_native/scripts/gen_locale_keys.sh from"
  echo "// lib/l10n/locale_keys.g.dart — do not edit by hand."
  echo
  echo "// swiftlint:disable identifier_name"
  echo "enum LocaleKeys {"
  perl -ne '
    BEGIN {
      %reserved = map { $_ => 1 } qw(
        associatedtype class deinit enum extension fileprivate func import init
        inout internal let open operator private precedencegroup protocol public
        rethrows static struct subscript typealias var break case catch continue
        default defer do else fallthrough for guard if in repeat return throw
        switch where while as false is nil self Self super throws true try Any
        Type);
    }
    if (/static const (\w+) = \x27([^\x27]*)\x27;/) {
      my ($name, $key) = ($1, $2);
      $name = "`$name`" if $reserved{$name};
      print "    static let $name = \"$key\"\n";
    }
  ' "$SRC"
  echo "}"
  echo "// swiftlint:enable identifier_name"
} > "$OUT"

echo "✓ $(grep -c 'static let' "$OUT") keys → $OUT"
