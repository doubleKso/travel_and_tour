#!/usr/bin/env bash
# Regenerates EpicWorld/Core/UI/Icons.swift: every Material icon the app uses,
# with the code point Flutter draws it from.
#
# The app bundles Flutter's own MaterialIcons font (see sync_resources.sh), so
# an icon looks identical on both stacks and Swift call sites read like Dart:
#
#   Dart:  Icon(Icons.home_rounded, size: 25, color: color)
#   Swift: Icon(Icons.home_rounded, size: 25, color: color)
#
# Icons are collected from lib/ (Dart, every name must exist) and from
# EpicWorld/ (Swift, unknown names such as ones in doc comments are skipped
# with a warning), so an icon referenced by new Swift code is picked up on the
# next run.
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
OUT="$HERE/EpicWorld/Core/UI/Icons.swift"

if [[ -z "${FLUTTER_ROOT:-}" ]] && command -v flutter >/dev/null 2>&1; then
  FLUTTER_ROOT="$(cd "$(dirname "$(command -v flutter)")/.." && pwd)"
fi
ICONS_DART="${FLUTTER_ROOT:?set FLUTTER_ROOT to the Flutter SDK}/packages/flutter/lib/src/material/icons.dart"

collect() { # $1 = dir, $2 = include glob, $3 = optional exclude
  { grep -rhoE '\bIcons\.[a-z_0-9]+' "$1" --include="$2" ${3:+--exclude="$3"} || true; } |
    sed 's/^Icons\.//' | sort -u | tr '\n' ' '
}
DART_USED="$(collect "$REPO/lib" '*.dart')"
SWIFT_USED="$(collect "$HERE/EpicWorld" '*.swift' 'Icons.swift')"

mkdir -p "$(dirname "$OUT")"
perl -0777 -e '
  my ($path, $dart, $swift) = @ARGV;
  open my $fh, "<", $path or die "cannot read $path";
  local $/; my $src = <$fh>;
  my %cp;
  while ($src =~ /static const IconData (\w+) = IconData\(\s*(0x[0-9a-fA-F]+)/g) {
    $cp{$1} = $2;
  }
  my %used;
  for my $name (split / /, $dart) {
    next unless length $name;
    die "unknown icon in lib/: $name\n" unless exists $cp{$name};
    $used{$name} = 1;
  }
  for my $name (split / /, $swift) {
    next unless length $name;
    if (exists $cp{$name}) { $used{$name} = 1 }
    else { print STDERR "  (skipping unknown Swift reference Icons.$name)\n" }
  }
  my %reserved = map { $_ => 1 } qw(associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private protocol public rethrows static struct subscript typealias var break case catch continue default defer do else fallthrough for guard if in repeat return throw switch where while as false is nil self super throws true try);
  print "// GENERATED by ios_native/scripts/gen_material_icons.sh from Flutter\x27s\n";
  print "// material/icons.dart — do not edit by hand.\n\n";
  print "// swiftlint:disable identifier_name\n";
  print "/// Material icons used by the app, keyed by their Flutter names.\n";
  print "enum Icons {\n";
  for my $name (sort keys %used) {
    my $id = $reserved{$name} ? "`$name`" : $name;
    printf "    static let %s = IconData(%s)\n", $id, lc $cp{$name};
  }
  print "}\n";
  print "// swiftlint:enable identifier_name\n";
' "$ICONS_DART" "$DART_USED" "$SWIFT_USED" > "$OUT"

echo "✓ $(grep -c 'static let' "$OUT") icons → $OUT"
